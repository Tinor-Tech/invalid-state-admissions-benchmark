#!/usr/bin/env node
// Regenerates baselines/results/. Deterministic except the wall-time column in SUMMARY.md.
//   node baselines/run-baselines.mjs          (or: npm run baselines)
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import os from "node:os";
import { ROOT, loadSpec, loadCases, loadGroundTruth } from "../lib/load.mjs";
import { schemaRegistry } from "../lib/schema.mjs";
import { runAll } from "../lib/runner.mjs";
import { scoreRun } from "../lib/score.mjs";
import { compactRow } from "../lib/report.mjs";
import { scoreDispositions, baselineDecisions } from "../lib/score-dispositions.mjs";

const out = join(ROOT, "baselines/results");
mkdirSync(out, { recursive: true });
const spec = loadSpec(), registry = await schemaRegistry();
const sets = { public: { cases: loadCases(ROOT, "cases"), truths: loadGroundTruth(ROOT, "ground-truth") }, probes: { cases: loadCases(ROOT, "probes/cases"), truths: loadGroundTruth(ROOT, "probes/ground-truth") } };
const strip = (run) => ({ ...run, outputs: Object.fromEntries(Object.entries(run.outputs).map(([k, v]) => { const { elapsedMs, ...rest } = v; return [k, rest]; })) });
export const summaryOf = (scored) => ({ adapter: scored.adapter, metrics: scored.metrics, families: Object.fromEntries(Object.entries(scored.families).map(([f, m]) => [f, { cases: m.units.cases, propositions: m.units.propositions, reads: m.units.reads, VSAR: m.ability.VSAR, CDR: m.ability.CDR, SRA: m.ability.SRA, IPAR: m.safety.IPAR, CPR: m.completion.CPR }])),
  cases: scored.cases.map((c) => ({ id: c.id, label: c.label, family: c.family, pass: c.pass, critical: c.critical.map((x) => x.type), failedPropositions: c.props.filter((p) => !p.fullyRight || p.invalidPersisted).map((p) => ({ id: p.id, declared: p.declared, diagnostics: p.diagnostics })), failedReads: c.reads.filter((r) => !r.ok).map((r) => ({ read: r.read, codes: r.codes })) })) });

const rows = [], timing = [];
for (const name of ["always-reject", "always-hold", "always-admit", "reference-rules"]) {
  const adapter = (await import(`../adapters/${name}.mjs`)).default;
  for (const [set, { cases, truths }] of Object.entries(sets)) {
    if (set === "probes" && name !== "reference-rules") continue;
    const run = await runAll(adapter, cases, spec, {}, registry);
    const scored = scoreRun({ spec, cases, truths, run });
    const tag = set === "public" ? name : `${name}.probes`;
    writeFileSync(join(out, `${tag}.output.json`), JSON.stringify(strip(run), null, 2) + "\n");
    writeFileSync(join(out, `${tag}.scores.json`), JSON.stringify(summaryOf(scored), null, 2) + "\n");
    rows.push({ set, ...compactRow(name, scored.metrics) });
    timing.push({ set, name, totalMs: Object.values(run.outputs).reduce((s, o) => s + o.elapsedMs, 0) });
  }
}
const l1 = ["always-reject", "always-hold", "always-admit"].map((b) => ({ b, m: scoreDispositions(sets.public.cases, sets.public.truths, baselineDecisions(sets.public.cases, b)).metrics }));
const f = (r) => (r.value === null ? "n/a" : `${r.num}/${r.den}`);
const md = [
  "# Baseline results (generated)",
  "",
  "Generated by `node baselines/run-baselines.mjs`. Everything except the wall-time table is deterministic and is checked by `test/baselines.test.mjs`.",
  "Metric definitions: [METRICS.md](../../METRICS.md). Safety metrics: lower is better. Ability and completion: higher is better.",
  "",
  "**Read before quoting.** The trivial baselines are explanations, not competitors. `reference-rules` was written by the benchmark authors with full knowledge of the public cases; its public-set score is an upper-bound illustration, not evidence that rules generalise. The probe set (7 paraphrases written after the baseline) shows how quickly it degrades. No language-model baseline has been run.",
  "",
  "## Level 2 (records and reads)",
  "",
  "| Set | Adapter | OAR | IPAR | UFR | DLR | VSAR | CDR | SRA | CPR | Critical | Errors |",
  "|---|---|---|---|---|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.set} | ${r.adapter} | ${r.OAR} | ${r.IPAR} | ${r.UFR} | ${r.DLR} | ${r.VSAR} | ${r.CDR} | ${r.SRA} | ${r.CPR} | ${r.critical} | ${r.errors} |`),
  "",
  "## Level 1 (declared dispositions only)",
  "",
  "| Baseline | CDR | OAR (decision) | VSAR (decision) | Outcome matches, reason ignored |",
  "|---|---|---|---|---|",
  ...l1.map(({ b, m }) => `| ${b} | ${f(m.CDR)} | ${f(m.OAR_decision)} | ${f(m.VSAR_decision)} | ${f(m.outcomeAccuracy)} |`),
  "",
  "## Execution cost (not deterministic)",
  "",
  `Wall time of the whole set on the machine that generated this file (${os.platform()} ${os.arch()}, Node ${process.version}). No model calls, tokens or money are involved in any of these adapters.`,
  "",
  "| Set | Adapter | Total ms |",
  "|---|---|---|",
  ...timing.map((t) => `| ${t.set} | ${t.name} | ${t.totalMs.toFixed(1)} |`),
  ""
].join("\n");
writeFileSync(join(out, "SUMMARY.md"), md);
console.log(md);
